        // Apply translations and dynamically update SEO Tags
        function applyLanguage(lang) {
            const data = translations[lang];
            
            document.title = data.meta_title;
            document.documentElement.setAttribute('lang', lang);

            let metaDesc = document.querySelector('meta[name="description"]');
            if (metaDesc) {
                metaDesc.setAttribute('content', data.meta_desc);
            }

            let ogTitle = document.querySelector('meta[property="og:title"]');
            if (ogTitle) ogTitle.setAttribute('content', data.meta_title);

            let ogDesc = document.querySelector('meta[property="og:description"]');
            if (ogDesc) ogDesc.setAttribute('content', data.meta_desc);

            let ogLocale = document.querySelector('meta[property="og:locale"]');
            if (ogLocale) ogLocale.setAttribute('content', lang === 'tr' ? 'tr_TR' : 'en_US');

            let twitterTitle = document.querySelector('meta[name="twitter:title"]');
            if (twitterTitle) twitterTitle.setAttribute('content', data.meta_title);

            let twitterDesc = document.querySelector('meta[name="twitter:description"]');
            if (twitterDesc) twitterDesc.setAttribute('content', data.meta_desc);

            // Translate all elements with data-i18n attribute safely without ignoring empty parameters
            document.querySelectorAll('[data-i18n]').forEach(el => {
                const key = el.getAttribute('data-i18n');
                if (data[key] !== undefined) {
                    el.innerHTML = data[key];
                }
            });

            // Translate placeholders dynamically
            document.querySelectorAll('[data-placeholder-tr]').forEach(el => {
                if (lang === 'tr') {
                    el.placeholder = el.getAttribute('data-placeholder-tr');
                } else {
                    el.placeholder = el.getAttribute('data-placeholder-en');
                }
            });

            // Update language switcher buttons text
            const btnText = lang === 'tr' ? 'EN' : 'TR';
            document.getElementById('langBtnText').innerText = btnText;
            document.getElementById('langBtnTextMobile').innerText = btnText;

            // Update static dynamic links
            const heroWaBtn = document.getElementById('hero_wa_btn');
            const floatingWa = document.getElementById('floating_wa');
            
            const encodedText = encodeURIComponent(data.wa_hero_text);
            if (heroWaBtn) heroWaBtn.href = `https://wa.me/905462359075?text=${encodedText}`;
            if (floatingWa) floatingWa.href = `https://wa.me/905462359075?text=${encodedText}`;
        }

